#!/bin/sh
# The company brain on this machine (Docker): Postgres + dashboard + local HTTPS. Docs: docs/LOCAL.md
#
#   sh deploy/local/brain-local.sh up       writes .env if missing (password, local network addresses), builds, starts, shows the address
#   sh deploy/local/brain-local.sh status   state of the containers and addresses
#   sh deploy/local/brain-local.sh ca       exports the root certificate (deploy/local/ca.crt), shows its fingerprint and how to install it here
#   sh deploy/local/brain-local.sh logs     live logs
#   sh deploy/local/brain-local.sh backup   Postgres backup into deploy/local/backups/
#   sh deploy/local/brain-local.sh update   git pull, rebuilds and restarts (the data stays)
#   sh deploy/local/brain-local.sh down     stops (the data stays in the Docker volumes)
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
ENV_FILE="$ROOT/.env"
CA_OUT="$ROOT/deploy/local/ca.crt"
cd "$ROOT"

say() { printf '%s\n' "$*"; }
fail() { printf '%s\n' "$*" >&2; exit 1; }
compose() { docker compose -f "$ROOT/compose.yaml" "$@"; }
envval() { grep "^$1=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- | sed 's/^"//; s/"$//'; }

command -v docker >/dev/null 2>&1 || fail "Docker not found: install Docker Desktop (macOS, Windows) or Docker Engine (Linux), then run again."
docker compose version >/dev/null 2>&1 || fail "\"docker compose\" not found: install Docker Compose v2, then run again."

# IPv4 addresses of this machine on the local network (excluding loopback and Docker).
lan_ips() {
  if command -v ip >/dev/null 2>&1; then
    ip -4 -o addr show scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | grep -v '^172\.1[6-9]\.\|^172\.2[0-9]\.\|^172\.3[01]\.' || true
  elif command -v ifconfig >/dev/null 2>&1; then
    ifconfig 2>/dev/null | awk '/inet / && $2 != "127.0.0.1" {print $2}' || true
  fi
}

default_hosts() {
  h="localhost"
  for ip in $(lan_ips); do h="$h, $ip"; done
  name=$(hostname -s 2>/dev/null || hostname 2>/dev/null || true)
  [ -n "$name" ] && h="$h, $name.local"
  printf '%s' "$h"
}

ensure_env() {
  [ -f "$ENV_FILE" ] && return 0
  pw=$(openssl rand -hex 16 2>/dev/null || head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
  hosts=$(default_hosts)
  first=$(printf '%s' "$hosts" | cut -d, -f2 | tr -d ' ')
  [ -n "$first" ] || first=localhost
  cat >"$ENV_FILE" <<ENV
# Self-hosted brain (read by compose.yaml). Can be edited; then: sh deploy/local/brain-local.sh up
POSTGRES_PASSWORD=$pw
# Names and addresses of the brain on the local network, all in the HTTPS certificate
BRAIN_HOSTS="$hosts"
# The one the computers will use (install prompt, links)
BRAIN_HOST=$first
# Certificate: internal (Caddy's private authority) or your files "/certs/cert.pem /certs/key.pem" (folder deploy/local/certs)
BRAIN_TLS=internal
# Claude on the server ("where does the company stand", onboarding): optional, each computer distills with its own subscription
ANTHROPIC_API_KEY=
# Fictitious demo company: BRAIN_DEMO=1
BRAIN_DEMO=
# BRAIN_SIGNUP=0 closes company creation from the home page (invitation only)
BRAIN_SIGNUP=
BRAIN_TIMEZONE=Europe/Paris
ENV
  say "Configuration written to $ENV_FILE (addresses: $hosts)."
}

trust_hint() {
  case "$(uname -s)" in
    Darwin) say "  security add-trusted-cert -r trustRoot -k \"\$HOME/Library/Keychains/login.keychain-db\" \"$CA_OUT\"" ;;
    Linux) say "  certutil -d sql:\$HOME/.pki/nssdb -A -t \"C,,\" -n \"NOS Brainer\" -i \"$CA_OUT\"   (Chrome; Firefox: Settings → Certificates → Import)" ;;
    *) say "  certutil -user -addstore Root \"$CA_OUT\"   (Windows)" ;;
  esac
}

export_ca() {
  if [ "$(envval BRAIN_TLS)" != "internal" ] && [ -n "$(envval BRAIN_TLS)" ]; then
    say "Certificate provided by you (BRAIN_TLS=$(envval BRAIN_TLS)): nothing to install on the computers if your authority is already trusted."
    return 0
  fi
  i=0
  while ! compose exec -T caddy cat /data/caddy/pki/authorities/local/root.crt >"$CA_OUT.tmp" 2>/dev/null || [ ! -s "$CA_OUT.tmp" ]; do
    i=$((i + 1))
    [ "$i" -lt 30 ] || { rm -f "$CA_OUT.tmp"; fail "Caddy has not created its authority yet: try again in a few seconds (sh deploy/local/brain-local.sh ca)."; }
    sleep 2
  done
  mv "$CA_OUT.tmp" "$CA_OUT"
  say "Root certificate exported: $CA_OUT"
  if command -v openssl >/dev/null 2>&1; then
    say "SHA-256 fingerprint: $(openssl x509 -in "$CA_OUT" -noout -fingerprint -sha256 | cut -d= -f2 | tr -d :)"
    say "(the same one is pinned in every install prompt generated by the dashboard)"
  fi
  say "For this machine's browser:"
  trust_hint
  say "The employees' computers have nothing to do: their install prompt takes care of it."
}

show_urls() {
  host=$(envval BRAIN_HOST)
  [ -n "$host" ] || host=localhost
  say ""
  say "The brain: https://$host   (also: $(envval BRAIN_HOSTS))"
  say "First time: https://$host/create creates the company and its first admin account."
  say "Then: /admin → Invite someone → the install prompt (certificate included) to paste into Claude Code on the computer."
}

cmd=${1:-help}
case "$cmd" in
  up)
    ensure_env
    say "Building and starting (the first time: a few minutes)…"
    compose up -d --build --wait
    export_ca
    show_urls
    ;;
  status)
    compose ps
    show_urls
    ;;
  ca) export_ca ;;
  logs) compose logs -f --tail=100 ;;
  backup)
    mkdir -p "$ROOT/deploy/local/backups"
    out="$ROOT/deploy/local/backups/brain-$(date +%Y%m%d-%H%M%S).sql.gz"
    compose exec -T postgres pg_dump -U brain brain | gzip >"$out"
    say "Backup: $out  (restore: gunzip -c <file> | docker compose exec -T postgres psql -U brain brain)"
    ;;
  update)
    git -C "$ROOT" pull --ff-only
    compose up -d --build --wait
    say "Updated and restarted."
    show_urls
    ;;
  down) compose down ;;
  help | -h | --help) sed -n 2,10p "$0" | sed 's/^# \{0,1\}//' ;;
  *) fail "Unknown command: $cmd (up, status, ca, logs, backup, update, down)" ;;
esac
